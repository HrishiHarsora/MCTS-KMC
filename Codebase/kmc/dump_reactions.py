"""
dump_reactions.py -- print the reaction table straight out of the engine.

    python dump_reactions.py              # markdown, to stdout
    python dump_reactions.py --csv        # csv instead
    python dump_reactions.py > REACTIONS.md

Every row is read from KMC.py's own `_RID_DESCRIPTION`, `_BASE_A`, `_BASE_EA`
and `_BASE_BETA`, so the documentation cannot drift away from what is actually
simulated. If a reaction is added or a catalog value changes, re-run this.
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import KMC


def rows():
    """(engine ID, reaction label, description, rate law, knobs, A, Ea, beta)."""
    for rid in range(1, KMC._NUM_RID):
        desc = KMC._RID_DESCRIPTION.get(rid, "")
        lab = KMC._rid_label(rid)
        src = KMC._TIED_RIDS.get(rid, rid)          # e.g. 4, 5 take 3's parameters
        if src in KMC._ARRHENIUS_RIDS:
            yield (rid, lab, desc, "Arrhenius", f"A_E{src}, Ea_E{src}, beta_E{src}",
                   KMC._BASE_A[rid], KMC._BASE_EA[rid], KMC._BASE_BETA[rid])
        else:
            el = "A" if rid in KMC._ASH_ADS_RIDS else "M"
            site = "terrace" if rid in KMC._TERRACE_ASH_RIDS + KMC._TERRACE_MMGA_RIDS else "step"
            knobs = f"S0_{el}_{site}, " + ("Ea_chem_As" if el == "A" else "Ea_chem_M")
            yield (rid, lab, desc, "impingement", knobs, None, None, None)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", action="store_true")
    a = ap.parse_args()

    R = list(rows())
    n_imp = sum(1 for r in R if r[3] == "impingement")
    n_arr = len(KMC._ARRHENIUS_RIDS)

    if a.csv:
        import csv
        w = csv.writer(sys.stdout, lineterminator="\n")
        w.writerow(["rid", "reaction", "description", "rate_law", "parameters",
                    "A", "Ea_K", "beta"])
        for rid, lab, desc, law, knobs, A, Ea, b in R:
            w.writerow([rid, lab, desc, law, knobs,
                        "" if A is None else repr(A),
                        "" if Ea is None else repr(Ea),
                        "" if b is None else repr(b)])
        return

    print("<!-- generated by dump_reactions.py -- do not hand-edit -->")
    print("# The reactions\n")
    print("## Reactions and the engine IDs that run them\n")
    print("A reaction is what the notes and the paper call R1, R2, ... . The engine runs "
          "some\nreactions as several IDs, because every event of one ID must have the "
          "same rate.\nEvent logs report counts by reaction; the engine ID is only a "
          "reference.\n")
    print("| reaction | name | engine IDs | cases |")
    print("|---|---|---|---|")
    for lab, name, ids in KMC._REACTIONS:
        cases = "; ".join(f"{KMC._RID_CASE[r]} = ID {r}" for r in ids if r in KMC._RID_CASE)
        print(f"| {lab} | {name} | {', '.join(str(r) for r in ids)} | {cases or '—'} |")
    print()
    print("- **R3**: the three IDs break the same As-H bond and share one parameter set "
          "(`A_E3`, `Ea_E3`, `beta_E3`).")
    print("- **R1, R2, R6, R7** (adsorption): terrace and step have their own sticking "
          "coefficients, `S0_A_terrace`,\n  `S0_A_step`, `S0_M_terrace`, `S0_M_step`, "
          "with S0_terrace <= S0_step enforced.")
    print("- **IDs 34, 35**: E4.2 (AsH on a D_MMGa) and E6.2 (MMGa on a D_AsH) with both "
          "upper sites free. The host has one\n  dangling bond, and its methyl / H moves "
          "out of the way, so the adsorbate can land on either site: two\n  events at half "
          "the rate each, so the host adsorbs at the rate of one site. With one site free, "
          "the\n  landing is an ordinary ID-6 / ID-9 event at the full rate.")
    print("- **R12-R17** (incorporation): the IDs of one reaction differ only in the partner, "
          "a spectator, and share one\n  parameter set: R12 `A_E14`, R13 `A_E17`, R14 `A_E26`, "
          "R15 `A_E20`, R16 `A_E29`, R17 `A_E23`.\n  Terrace or step is decided on either "
          "side: a step if the host's or the partner's other upper bond\n  holds an "
          "incorporated atom.")
    print("- **IDs 36-77** (27 Sep): methyl removal from an adsorbed MMGa (R8, ID 36); desorption of "
          "an adsorbed Ga\n  (R18) and its terrace / step incorporation (R19, R20); a partner below that "
          "is an adsorbed\n  precursor of the other element (IDs 44-59, cases of R12-R17, R19, R20); "
          "desorption of every film\n  atom with two / three bonds at R10 / R11's rate (IDs 60-65); a "
          "film atom's free bond bonding\n  down to a free bond below (IDs 66-77, cases of its kind's "
          "incorporation). No bond forms\n  automatically: an H or a methyl rotates out of the way, and "
          "every bond is one of these events.\n")
    print(f"## Every engine ID\n")
    print(f"{len(R)} engine IDs. {len(R) - n_imp} carry an Arrhenius rate "
          f"k = A x T^beta x exp(-Ea/T), with **Ea in kelvin**;\nthe remaining "
          f"{n_imp} are adsorption events whose rate comes from the impingement "
          f"flux,\nnot from a prefactor and a barrier. Parameter names keep the "
          f"engine ID (`A_E12` is ID 12).\n")
    print("| reaction | engine ID | process | rate law | tunable by | A | Ea [K] | beta |")
    print("|---|---|---|---|---|---|---|---|")
    for rid, lab, desc, law, knobs, A, Ea, b in R:
        if A is None:
            print(f"| {lab} | {rid} | {desc} | impingement | `{knobs}` | — | — | — |")
        else:
            ks = ", ".join(f"`{k}`" for k in knobs.split(", "))
            print(f"| {lab} | {rid} | {desc} | Arrhenius | {ks} "
                  f"| {A:.3g} | {Ea:.1f} | {b:g} |")

    print("\n## Species names\n")
    print("| symbol | meaning |")
    print("|---|---|")
    legend = [("V_As, V_Ga", "vacant As / Ga site"),
              ("S_As, S_Ga", "substrate As / Ga"),
              ("As, Ga", "fully incorporated bulk atom"),
              ("D_X, DD_X", "X with one / two dangling bonds"),
              ("DDD_As, DDD_Ga", "As / Ga with one bond and three dangling bonds (adsorbed)"),
              ("MMGa", "monomethylgallium, CH3-Ga"),
              ("AsH", "arsenic hydride")]
    for a_, b_ in legend:
        print(f"| `{a_}` | {b_} |")

    print("\n## The six parameters that are not per-reaction\n")
    print("| parameter | enters |")
    print("|---|---|")
    sd = KMC._STICK_DEFAULTS
    print("| `S0_A_terrace`, `S0_A_step` | AsH sticking probability `S0 x exp(-Ea_chem_As/T)` on a "
          "terrace, engine IDs 6, 7, 34 (R1; catalog %g), and at a step, ID 8 (R2; catalog %g) |"
          % (sd["S0_A_terrace"], sd["S0_A_step"]))
    print("| `S0_M_terrace`, `S0_M_step` | the same for MMGa: IDs 9, 10, 35 (R6; catalog %g) "
          "and ID 11 (R7; catalog %g) |" % (sd["S0_M_terrace"], sd["S0_M_step"]))
    print("| `Ea_chem_As`, `Ea_chem_M` | the sticking barriers (catalog %g K each) |" % sd["Ea_chem_As"])
    print("\nOrdering constraints, checked on every run (`KMC._CONSTRAINTS`): "
          + "; ".join(f"`{a}` {op} `{b}`" for a, op, b in KMC._CONSTRAINTS) + ".")
    print("\nThe partial pressures are fixed in the engine at the experiment's "
          "values\n(608 and 65.86 Pa, standing for AsH and MMGa), so `S0` carries that degree of "
          "freedom: only the\nproduct `pressure x S0` enters an impingement "
          "rate.")
    print("\nTotal: %d x 3 Arrhenius parameters + 6 = %d."
          % (n_arr, 3 * n_arr + 6))


if __name__ == "__main__":
    main()
